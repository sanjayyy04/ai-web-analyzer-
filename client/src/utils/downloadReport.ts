import type { AnalyzeResponse } from "../types";

const SCORE_LABELS: Record<string, string> = {
  performance: "Performance",
  accessibility: "Accessibility",
  seo: "SEO",
  "best-practices": "Best practices",
  ux: "UX",
  content: "Content",
};

function siteSlug(url: string): string {
  try {
    return new URL(url).hostname.replace(/\./g, "-");
  } catch {
    return "website";
  }
}

function timestampSlug(iso: string): string {
  return iso.slice(0, 10);
}

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function downloadBlob(content: string, filename: string, mime: string) {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = filename;
  anchor.rel = "noopener";
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  URL.revokeObjectURL(url);
}

export function buildMarkdownReport(data: AnalyzeResponse): string {
  const lines: string[] = [];

  lines.push("# AI Website Analyzer — Full Report");
  lines.push("");
  lines.push(`- **URL:** ${data.url}`);
  lines.push(`- **Generated:** ${new Date(data.fetchedAt).toLocaleString()}`);
  if (data.aiModel) lines.push(`- **Report engine:** ${data.aiModel}`);
  if (data.note) lines.push(`- **Note:** ${data.note}`);
  if (data.auditMeta) {
    lines.push(
      `- **Lighthouse:** v${data.auditMeta.lighthouseVersion}, form factor: ${data.auditMeta.formFactor}`,
    );
    lines.push(
      `- **Extra categories:** ${data.auditMeta.extraCategories.join(", ")} (not in Chrome DevTools Lighthouse)`,
    );
  }
  lines.push("");

  lines.push("## Scores");
  lines.push("");
  lines.push("| Category | Score |");
  lines.push("|----------|-------|");
  for (const [key, label] of Object.entries(SCORE_LABELS)) {
    const v = data.scores[key];
    lines.push(`| ${label} | ${v === null || v === undefined ? "—" : `${v}/100`} |`);
  }
  lines.push("");

  lines.push("## Developer report");
  lines.push("");

  for (const section of data.report) {
    lines.push(`### ${section.headline}`);
    lines.push("");

    if (section.findings.length === 0) {
      lines.push("_No findings in this section._");
      lines.push("");
      continue;
    }

    section.findings.forEach((f, i) => {
      lines.push(`#### ${i + 1}. ${f.summary}`);
      lines.push("");
      lines.push("**Impact**");
      lines.push("");
      lines.push(f.impact);
      lines.push("");
      lines.push("**AI Fix**");
      lines.push("");
      lines.push(f.fix);
      lines.push("");
      if (f.sampleCode) {
        const lang = f.codeLanguage ?? "html";
        lines.push("**Sample code**");
        lines.push("");
        lines.push("```" + lang);
        lines.push(f.sampleCode.trim());
        lines.push("```");
        lines.push("");
      }
      if (f.relatedAuditIds?.length) {
        lines.push(`_Audit IDs: ${f.relatedAuditIds.join(", ")}_`);
        lines.push("");
      }
      lines.push("---");
      lines.push("");
    });
  }

  lines.push("---");
  lines.push("");
  lines.push("_Generated by AI Website Analyzer._");

  return lines.join("\n");
}

export function buildHtmlReport(data: AnalyzeResponse): string {
  const scoreRows = Object.entries(SCORE_LABELS)
    .map(([key, label]) => {
      const v = data.scores[key];
      const score = v === null || v === undefined ? "—" : `${v}/100`;
      return `<tr><td>${escapeHtml(label)}</td><td><strong>${score}</strong></td></tr>`;
    })
    .join("");

  const sectionsHtml = data.report
    .map((section) => {
      const findingsHtml = section.findings
        .map((f, i) => {
          const codeBlock = f.sampleCode
            ? `<p><strong>Sample code</strong></p><pre><code>${escapeHtml(f.sampleCode.trim())}</code></pre>`
            : "";
          return `
        <article class="finding">
          <h4>${i + 1}. ${escapeHtml(f.summary)}</h4>
          <p><strong>Impact</strong></p>
          <p>${escapeHtml(f.impact)}</p>
          <p><strong>AI Fix</strong></p>
          <p>${escapeHtml(f.fix)}</p>
          ${codeBlock}
        </article>`;
        })
        .join("");

      return `
      <section>
        <h3>${escapeHtml(section.headline)}</h3>
        ${findingsHtml || "<p><em>No findings.</em></p>"}
      </section>`;
    })
    .join("");

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>Audit Report — ${escapeHtml(data.url)}</title>
  <style>
    :root { color-scheme: dark; }
    body { font-family: "Segoe UI", system-ui, sans-serif; max-width: 1360px; margin: 2rem auto; padding: 0 clamp(1rem, 2.5vw, 2.25rem) 3rem; line-height: 1.65; color: #f4f5f1; background: #000000; }
    h1 { font-size: 1.75rem; border-bottom: 3px solid #b4eb58; padding-bottom: 0.5rem; }
    h2 { font-size: 1.35rem; margin-top: 2rem; color: #ead35a; }
    h3 { font-size: 1.1rem; margin-top: 1.75rem; padding-bottom: 0.25rem; border-bottom: 1px solid #2b302a; }
    h4 { font-size: 1rem; margin: 1.25rem 0 0.5rem; }
    .meta { background: #111311; border: 1px solid #2b302a; border-radius: 8px; padding: 1rem 1.25rem; margin: 1rem 0; }
    table { width: 100%; border-collapse: collapse; margin: 1rem 0; }
    th, td { border: 1px solid #2b302a; padding: 0.6rem 1rem; text-align: left; }
    th { background: #111311; }
    .finding { margin: 1rem 0 1.5rem; padding-bottom: 1rem; border-bottom: 1px dashed #454c42; }
    pre { background: #111311; color: #b4eb58; padding: 1rem; border: 1px solid #2b302a; border-radius: 4px; overflow-x: auto; font-size: 0.8rem; white-space: pre-wrap; }
    @media print { body { margin: 0; max-width: none; } }
  </style>
</head>
<body>
  <h1>AI Website Analyzer — Full Report</h1>
  <div class="meta">
    <p><strong>URL:</strong> ${escapeHtml(data.url)}</p>
    <p><strong>Generated:</strong> ${escapeHtml(new Date(data.fetchedAt).toLocaleString())}</p>
    ${data.aiModel ? `<p><strong>Report engine:</strong> ${escapeHtml(data.aiModel)}</p>` : ""}
    ${data.note ? `<p><strong>Note:</strong> ${escapeHtml(data.note)}</p>` : ""}
  </div>
  <h2>Scores</h2>
  <table>
    <thead><tr><th>Category</th><th>Score</th></tr></thead>
    <tbody>${scoreRows}</tbody>
  </table>
  <h2>Developer report</h2>
  ${sectionsHtml}
  <p style="margin-top:2rem;color:#a5aaa1;font-size:0.875rem;">Generated by AI Website Analyzer.</p>
</body>
</html>`;
}

export type ReportFormat = "markdown" | "json" | "html";

export function downloadFullReport(data: AnalyzeResponse, format: ReportFormat) {
  const slug = siteSlug(data.url);
  const date = timestampSlug(data.fetchedAt);

  switch (format) {
    case "markdown": {
      downloadBlob(
        buildMarkdownReport(data),
        `audit-report-${slug}-${date}.md`,
        "text/markdown;charset=utf-8",
      );
      break;
    }
    case "json": {
      downloadBlob(
        JSON.stringify(data, null, 2),
        `audit-report-${slug}-${date}.json`,
        "application/json;charset=utf-8",
      );
      break;
    }
    case "html": {
      downloadBlob(
        buildHtmlReport(data),
        `audit-report-${slug}-${date}.html`,
        "text/html;charset=utf-8",
      );
      break;
    }
  }
}
